#!/usr/bin/env python3
"""Generate `core/src/codepage_tables.rs` from Python's built-in codecs.

Usage (from the repo root):

    python3 core/tools/gen_codepages.py > core/src/codepage_tables.rs
    cargo fmt --all

Only the upper half (0x80-0xFF) is generated; 0x20-0x7F is the Epson
"Common Page" (ASCII, with 0x7F printed as a space) and is handled in code.

Deviation from Python's cp1252 codec: 0x81, 0x8D, 0x8F, 0x90 and 0x9D are
undefined in Windows-1252 (the codec raises); the Epson table for page 16
[WPC1252] prints them as spaces ("SP"), so they map to U+0020 here.
"""

TABLES = [
    ("CP437", "cp437"),
    ("CP850", "cp850"),
    ("CP860", "cp860"),
    ("CP858", "cp858"),
    ("WINDOWS_1252", "cp1252"),
]


def upper_half(codec):
    out = []
    for b in range(0x80, 0x100):
        try:
            out.append(bytes([b]).decode(codec))
        except UnicodeDecodeError:
            out.append(" ")
    assert all(len(c) == 1 for c in out)
    return out


def main():
    print("// @generated by core/tools/gen_codepages.py - do not edit by hand.")
    print("//! Upper halves (0x80-0xFF) of the supported single-byte code pages.")
    print()
    for name, codec in TABLES:
        chars = upper_half(codec)
        print(f"/// Bytes 0x80-0xFF of `{codec}` (Python codec), as Unicode scalars.")
        print(f"pub(crate) const {name}: [char; 128] = [")
        for row in range(0, 128, 8):
            cells = ", ".join(f"'\\u{{{ord(c):04X}}}'" for c in chars[row:row + 8])
            print(f"    {cells}, // 0x{0x80 + row:02X}")
        print("];")
        print()


if __name__ == "__main__":
    main()
